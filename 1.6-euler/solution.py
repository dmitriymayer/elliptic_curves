from math import asin, sin, sqrt

def F(u, steps=2000):
    """Длина дуги лемнискаты от центра до точки на расстоянии u:
    ∫₀ᵘ dt/√(1 − t⁴). Замена t = sin φ убирает особенность в t = 1:
    подынтегральная функция становится 1/√(1 + sin²φ)."""
    b = asin(u)
    h = b / steps
    f = lambda phi: 1 / sqrt(1 + sin(phi)**2)
    s = f(0) + f(b) + sum((4 if k % 2 else 2) * f(k * h) for k in range(1, steps))
    return s * h / 3                          # формула Симпсона

def euler(u1, u2):
    """Правая часть формулы Эйлера: только корни и арифметика."""
    return (u1 * sqrt(1 - u2**4) + u2 * sqrt(1 - u1**4)) / (1 + u1**2 * u2**2)

quarter = F(1)                                # четверть лемнискаты, ϖ/2
print(f"ϖ/2 = {quarter:.15f}")

for u1, u2 in [(0.1, 0.2), (0.3, 0.5), (0.5, 0.5), (0.6, 0.65)]:
    U = euler(u1, u2)
    print(f"u1 = {u1}, u2 = {u2}:  U = {U:.12f},  "
          f"F(u1) + F(u2) − F(U) = {F(u1) + F(u2) - F(U):+.1e}")

# Фаньяно: удвоение дуги до u = √(√2 − 1) приводит ровно в вершину
u = sqrt(sqrt(2) - 1)
print(f"удвоение u = √(√2 − 1):  U = {euler(u, u):.15f}")

# Дуги вместе длиннее четверти: формула для интегралов ломается
u1, u2 = 0.9, 0.8
s, U = F(u1) + F(u2), euler(u1, u2)
print(f"u1 = 0.9, u2 = 0.8:  F(u1) + F(u2) − F(U) = {s - F(U):+.6f},"
      f"  а ϖ − (F(u1) + F(u2)) − F(U) = {2*quarter - s - F(U):+.1e}")
